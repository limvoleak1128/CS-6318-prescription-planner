"""
A simple, separate implementation of the same safety judgments. FOR CROSS-CHECKING ONLY.

This is NOT the forward chainer. It applies the fact tables directly, with plain loops, so it is easy to
read and easy to trust. The real program (kb.py) uses a genuine forward chainer. The tests then check
that the real program and this file agree.

Do not edit this file: it is the independent cross-check.
"""
from itertools import product

import kb_facts as facts


def build_attributes(patient):
    """Return the set of attributes the patient has: typed ones plus ones built from numbers."""
    attributes = set(patient.get("has", []))
    age = patient.get("age")
    egfr = patient.get("egfr")
    weight = patient.get("weight")
    creatinine = patient.get("creatinine")

    if age is not None and age >= facts.ELDERLY_AGE_YEARS:
        attributes.add("Elderly")
    if age is not None and age >= facts.VERY_OLD_AGE_YEARS:
        attributes.add("AgeAtLeast80")
    if egfr is not None and egfr < facts.SEVERE_KIDNEY_EGFR_BELOW:
        attributes.add("SevereKidneyImpairment")
    if egfr is not None and facts.SEVERE_KIDNEY_EGFR_BELOW <= egfr < facts.MODERATE_KIDNEY_EGFR_BELOW:
        attributes.add("ModerateKidneyImpairment")
    if weight is not None and weight <= facts.LOW_WEIGHT_KG_AT_MOST:
        attributes.add("LowWeight")
    if creatinine is not None and creatinine >= facts.HIGH_CREATININE_AT_LEAST:
        attributes.add("HighCreatinine")
    if "ModerateLiverImpairment" in attributes or "SevereLiverImpairment" in attributes:
        attributes.add("ActiveLiverDisease")
    return attributes


def judge_regimen(patient, regimen):
    """
    Judge a regimen (a tuple of drug names, complete or partial).
    Returns a dict:
      rejected    list of (drug, reason)
      flag_labels list of labels such as "Glipizide:ModerateKidneyImpairment" or "Warfarin+Ibuprofen:Moderate"
      points      total ranking points
      flag_count  number of flags
      dose_note   True if the Apixaban dose note applies
    """
    attributes = build_attributes(patient)
    pregnant = bool(patient.get("pregnant", False))
    allergies = set(patient.get("allergies", []))
    rejected = []
    flag_labels = []
    points = 0

    for drug in regimen:
        if drug in allergies:
            rejected.append((drug, "Allergy"))
        for rejecting_drug, attribute in facts.REJECT_IF_HAS:
            if rejecting_drug == drug and attribute in attributes:
                rejected.append((drug, attribute))
        for flagging_drug, attribute in facts.FLAG_IF_HAS:
            if flagging_drug == drug and attribute in attributes:
                flag_labels.append(f"{drug}:{attribute}")
                points += facts.OTHER_FLAG_POINTS
        if pregnant and drug in facts.REJECT_IF_PREGNANT:
            rejected.append((drug, "Pregnancy"))
        if pregnant and drug in facts.FLAG_IF_PREGNANT:
            flag_labels.append(f"{drug}:Pregnancy")
            points += facts.OTHER_FLAG_POINTS

    for first, second, severity in facts.INTERACTIONS:
        if first in regimen and second in regimen:
            if severity == "Major":
                rejected.append((first, f"InteractionWith({second})"))
            else:
                flag_labels.append(f"{first}+{second}:Moderate")
                points += facts.MODERATE_INTERACTION_POINTS

    dose_note = False
    if "Apixaban" in regimen:
        matches = sum(1 for a in facts.APIXABAN_DOSE_NOTE_ATTRIBUTES if a in attributes)
        if matches >= facts.APIXABAN_DOSE_NOTE_MINIMUM:
            dose_note = True
            flag_labels.append("Apixaban:DoseNote")
            points += facts.DOSE_NOTE_POINTS

    flag_count = sum(1 for label in flag_labels if not label.endswith(":DoseNote"))
    return {"rejected": rejected, "flag_labels": flag_labels, "points": points,
            "flag_count": flag_count, "dose_note": dose_note}


def candidate_lists(patient):
    """One list of candidate drugs for each condition the patient needs, in the patient's order."""
    return [facts.CONDITIONS[condition] for condition in patient["needs"]]


def count_states_generated(patient):
    """Count the states a depth-first search with pruning creates (root included)."""
    needs = patient["needs"]
    generated = 1

    def expand(chosen):
        nonlocal generated
        index = len(chosen)
        if index == len(needs):
            return
        for drug in facts.CONDITIONS[needs[index]]:
            generated += 1
            attempt = chosen + (drug,)
            if not judge_regimen(patient, attempt)["rejected"]:
                expand(attempt)

    expand(())
    return generated


def plan_reference(patient):
    """Try every complete regimen and rank the valid ones. Slow but simple."""
    all_regimens = list(product(*candidate_lists(patient)))
    valid = []
    for regimen in all_regimens:
        judged = judge_regimen(patient, regimen)
        if not judged["rejected"]:
            valid.append((regimen, judged["points"], judged["flag_count"], judged["dose_note"]))
    valid.sort(key=lambda row: (row[1], row[2], row[3], row[0]))

    blocked = []
    if not valid:
        for condition in patient["needs"]:
            allowed = [d for d in facts.CONDITIONS[condition] if not judge_regimen(patient, (d,))["rejected"]]
            if not allowed:
                blocked.append(condition)

    winners = []
    if valid:
        best = (valid[0][1], valid[0][2], valid[0][3])
        winners = [row[0] for row in valid if (row[1], row[2], row[3]) == best]

    return {
        "regimen_count": len(all_regimens),
        "invalid_count": len(all_regimens) - len(valid),
        "ranked": valid,
        "winners": winners,
        "blocked_conditions": blocked,
        "states_generated": count_states_generated(patient),
        "full_tree_size": 2 ** (len(patient["needs"]) + 1) - 1,
    }
